def text(x, y, label, *, bold=False, align='center', color=INK):
    artist = ax.text(x, y, label, ha=align, va='center', fontsize=7,
                     color=color, fontweight='bold' if bold else 'normal',
                     linespacing=1.28, zorder=5)
    texts.append(artist)
    return artist

def box(x, y, w, h, *, title=None, body=None, edge=BLUE, fill='white'):
    patch = FancyBboxPatch((x, y), w, h,
                          boxstyle='round,pad=0,rounding_size=1.1',
                          edgecolor=edge, facecolor=fill, linewidth=0.65,
                          zorder=2)
    ax.add_patch(patch)
    boxes.append({'bbox_mm': [x, y, x + w, y + h],
                  'title': title, 'body': body})
    if title and body:
        text(x + w / 2, y + h - 4.0, title, bold=True)
        text(x + w / 2, y + h / 2 - 2.2, body)
    else:
        text(x + w / 2, y + h / 2, title or body,
             bold=bool(title))

def arrow(points, *, color=BLUE, width=0.75):
    points = [(float(x), float(y)) for x, y in points]
    path = MplPath(points, [MplPath.MOVETO] +
                   [MplPath.LINETO] * (len(points) - 1))
    artist = FancyArrowPatch(path=path, arrowstyle='-|>',
                             mutation_scale=5.7, linewidth=width,
                             edgecolor=color, facecolor=color, fill=True,
                             capstyle='round', joinstyle='miter', zorder=3)
    ax.add_patch(artist)
    routes.append({'points_mm': points, 'color': color})

